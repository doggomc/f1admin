'use strict';
const assert = require('node:assert/strict');
const { PNG } = require('pngjs');
const { createResultsPublisher, createResultsService, jolpiRaceResult, openF1Rows, openF1Time, duration, keyFor, resultsChannel, resultPayload, matchingSession } = require('../bot/results-service');
const { svgForResults, logoFor } = require('../bot/results-image');
const fs = require('fs');
const race = JSON.parse(fs.readFileSync(require('path').join(__dirname,'fixtures','sample-results.json'),'utf8'));
async function main() {
  const raceResult=jolpiRaceResult(race);
  assert.equal(raceResult.rows[0].time,'1:30:00.000');
  assert.equal(raceResult.rows[8].time,'+ 1 LAP');
  assert.equal(raceResult.rows[9].time,'DNF');
  assert.equal(raceResult.rows[0].color,'#ff8000');
  assert.equal(logoFor('RB F1 Team'),'racingbulls');
  assert.equal(duration(71.234),'1:11.234');
  assert.equal(openF1Time({position:2,gap_to_leader:1.234},'race'),'+ 1.234');
  assert.equal(openF1Time({duration:[73.2,72.4,71.2]},'timed'),'1:11.200');
  assert.equal(openF1Time({dnf:true},'race'),'DNF');
  assert(svgForResults(raceResult).includes('RACE RESULTS'));
  const payload = resultPayload(raceResult,'guild','result-key');
  assert.equal(payload.files[0].name,'freef1-session-results.png');
  assert(payload.files[0].attachment.length < 100_000);
  assert.equal(PNG.sync.read(payload.files[0].attachment).width,960);
  assert(payload.enforceNonce); assert.equal(payload.nonce.length,24);
  assert.deepEqual(payload.allowedMentions,{parse:[]});
  const t=Date.parse('2026-11-13T12:00:00Z');
  const season=[{round:20,slug:'brazil',name:'Brazilian Grand Prix',sessions:[{slug:'race',name:'Race',ts:t-5*86400_000}]}, {round:21,slug:'test',name:'Test Grand Prix',sessions:[{slug:'fp1',name:'Practice 1',ts:t+3600_000}]}];
  race.round='20';
  let sends=[], gets=0, held = new Set();
  const channel={name:'results',type:0,async send(payload){sends.push(payload);return{id:'m'+sends.length}}};
  const guild={channels:{cache:new Map([['channel',channel]])}};
  const client={guilds:{cache:new Map([['guild',guild]])}};
  let snapshot={guilds:{guild:{sent:{}}}};
  const store={async load(){return snapshot},async save(){},async claimAlert(g,k){if(held.has(k))return{acquired:false};held.add(k);return{acquired:true,async release(){held.delete(k)}}}};
  const result={event:'Test Grand Prix',session:'Practice 1',kind:'timed',rows:raceResult.rows};
  const service={async latestRace(){gets++;return race},async sessionResults(){return result}};
  const make=()=>createResultsPublisher({store,client,season,service,payloadBuilder:(r,g,k)=>({key:k})});
  let pub=make(); await pub('guild',snapshot.guilds.guild,t);
  assert.equal(sends.length,1,'latest race posts on initial run');
  assert(snapshot.guilds.guild.sent[keyFor(season[0],season[0].sessions[0])]);
  assert(snapshot.guilds.guild.sent['results:bootstrap']);
  await pub('guild',snapshot.guilds.guild,t+60_000);
  pub=make(); await pub('guild',snapshot.guilds.guild,t+120_000);
  assert.equal(sends.length,1,'no duplicate on restart'); assert.equal(gets,1);
  await pub('guild',snapshot.guilds.guild,t+3600_000+40*60_000);
  assert.equal(sends.length,2,'later session posted');
  pub=make(); await pub('guild',snapshot.guilds.guild,t+3600_000+45*60_000);
  assert.equal(sends.length,2,'later result not reposted after restart');
  // A temporary provider failure must retry rather than marking the race as posted.
  let retryState={guilds:{guild:{sent:{}}}}, attempts=0, retrySends=0;
  const retryStore={async load(){return retryState},async save(){},async claimAlert(){return{acquired:true,async release(){}}}};
  const retryChannel={name:'results',type:0,async send(){retrySends++;return{id:'retry'}}};
  const retryClient={guilds:{cache:new Map([['guild',{channels:{cache:new Map([['r',retryChannel]])}}]])}};
  const retryService={async latestRace(){if(++attempts===1)throw Error('offline');return race},async sessionResults(){return null}};
  const retryPublisher=createResultsPublisher({store:retryStore,client:retryClient,season,service:retryService,payloadBuilder:()=>({})});
  await retryPublisher('guild',retryState.guilds.guild,t);
  assert.equal(retrySends,0); assert(!retryState.guilds.guild.sent['results:bootstrap']);
  await retryPublisher('guild',retryState.guilds.guild,t+30_000);
  assert.equal(retrySends,1); assert(retryState.guilds.guild.sent['results:bootstrap']);
  assert.equal(resultsChannel({channels:{cache:new Map([['1',channel],['2',{...channel}]])}}),null,'ambiguous channel not selected');
  const newer={session_name:'Practice 1',date_start:new Date(t).toISOString(),session_key:10};
  assert.equal(matchingSession([newer],{name:'Practice 1',ts:t}).session_key,10);
  const drivers=Array.from({length:10},(_,i)=>({driver_number:i+1,first_name:'Driver',last_name:String(i+1),team_name:'Ferrari',team_colour:'ff0000'}));
  const rows=drivers.map((d,i)=>({position:i+1,driver_number:d.driver_number,duration:71+i}));
  assert.equal(openF1Rows(rows,drivers,'timed').length,10);
  assert.equal(openF1Rows(rows.slice(0,5),drivers,'timed'),null,'do not publish partial results');
  let requests=[];
  const network=async url=>{requests.push(url); const data=url.includes('/sessions?')?[{...newer,date_end:new Date(t+3600_000).toISOString()}]:url.includes('/session_result?')?rows:drivers;return{ok:true,json:async()=>data}};
  const api=createResultsService({fetchImpl:network,now:()=>t+2*3600_000});
  assert((await api.sessionResults({name:'Test'}, {name:'Practice 1',slug:'fp1',ts:t}, t-1000)).rows.length===10);
  assert.equal((await api.sessionResults({name:'Test'}, {name:'Practice 1',slug:'fp1',ts:t}, t+2*3600_000)).skipped,true);
  console.log(`Discord results: image ${payload.files[0].attachment.length} bytes, times, completeness, one-time last race, future session, restart deduplication passed`);
}
main().catch(e=>{console.error(e);process.exitCode=1});
